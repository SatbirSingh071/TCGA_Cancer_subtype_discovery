"""Programmatically builds the eight analysis notebooks in notebooks/.

Why generate notebooks with a script rather than hand-author raw .ipynb JSON?
Every notebook shares the same repo-root path setup, config loading, and
plotting conventions; generating them from one script keeps that boilerplate
consistent and makes it trivial to regenerate all eight after a src/ change.
Each notebook is executed with ``jupyter nbconvert --execute`` immediately
after generation (see the bottom of this file / ``Makefile``-equivalent
instructions in the README) so that the committed .ipynb files contain real,
reproducible outputs -- not placeholders.
"""
from __future__ import annotations

from pathlib import Path

import nbformat as nbf

REPO_ROOT = Path(__file__).resolve().parents[1]
NOTEBOOKS_DIR = REPO_ROOT / "notebooks"

SETUP_CODE = '''\
import sys
from pathlib import Path

REPO_ROOT = Path.cwd().parent if (Path.cwd() / ".." / "src").exists() else Path.cwd()
sys.path.insert(0, str(REPO_ROOT))

import warnings
warnings.filterwarnings("ignore")

import numpy as np
import pandas as pd
from IPython.display import Image, display

from src.config import load_config
from src.logging_config import setup_logging

setup_logging()
cfg = load_config(REPO_ROOT / "config.yaml")
FIGURES = REPO_ROOT / "figures"
RESULTS = REPO_ROOT / "results"
REPORTS = REPO_ROOT / "reports"
pd.set_option("display.max_columns", 50)
pd.set_option("display.width", 140)
print(f"Repo root: {REPO_ROOT}")
print(f"Cancer type: {cfg['project']['cancer_type']}")
'''


def md(src: str) -> nbf.NotebookNode:
    return nbf.v4.new_markdown_cell(src)


def code(src: str) -> nbf.NotebookNode:
    return nbf.v4.new_code_cell(src)


def new_notebook(cells: list[nbf.NotebookNode]) -> nbf.NotebookNode:
    nb = nbf.v4.new_notebook()
    nb["cells"] = cells
    nb["metadata"] = {
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python", "version": "3.11"},
    }
    return nb


def write(nb: nbf.NotebookNode, filename: str) -> None:
    path = NOTEBOOKS_DIR / filename
    nbf.write(nb, path)
    print(f"Wrote {path}")



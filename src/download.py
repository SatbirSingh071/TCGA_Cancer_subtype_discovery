"""Automated data acquisition from the NCI Genomic Data Commons (GDC) API.

This module implements a real, working client against the public GDC REST
API (https://api.gdc.cancer.gov). It is used to:

1. Query the ``files`` endpoint for RNA-seq gene expression quantification
   files (STAR - Counts workflow) belonging to a given TCGA project.
2. Download each file's gene-level TPM values via the ``data`` endpoint.
3. Query the ``cases`` endpoint for matched clinical/demographic/follow-up
   metadata (age, sex, tumor stage, vital status, days to death/last
   follow-up) needed for the clinical and survival analyses downstream.
4. Assemble everything into a single genes x samples expression matrix and
   a samples x clinical-fields metadata table, written to ``data/raw`` and
   ``data/metadata`` respectively.

Design notes
------------
* GDC hosts ~1,100 TCGA-BRCA RNA-seq cases. A full pull is several hundred
  megabytes and tens of thousands of small HTTP requests-worth of case
  metadata; this is a legitimate real-world workload but impractical to run
  unattended in a lightweight demo environment. ``max_cases`` in
  ``config.yaml`` lets you request a fast, real subset (default: 60 cases)
  for a genuine end-to-end smoke test, or set it to ``null`` for a full
  production pull.
* An equivalent R/TCGAbiolinks script (``scripts/download_tcgabiolinks.R``,
  generated by :func:`write_tcgabiolinks_script`) is provided because
  TCGAbiolinks is the de-facto standard tool in the TCGA community and many
  reviewers will expect to see it alongside a pure-Python GDC client.
"""
from __future__ import annotations

import gzip
import io
import time
from pathlib import Path
from typing import Any

import pandas as pd
import requests

from .config import load_config, resolve_path
from .logging_config import get_logger

log = get_logger(__name__)

GDC_FILES_ENDPOINT = "/files"
GDC_DATA_ENDPOINT = "/data"
GDC_CASES_ENDPOINT = "/cases"

REQUEST_TIMEOUT = 60
RETRY_ATTEMPTS = 3
RETRY_BACKOFF_SECONDS = 2


# --------------------------------------------------------------------------- #
# Low-level HTTP helpers
# --------------------------------------------------------------------------- #
def _post_with_retry(url: str, payload: dict) -> requests.Response:
    last_exc: Exception | None = None
    for attempt in range(1, RETRY_ATTEMPTS + 1):
        try:
            resp = requests.post(url, json=payload, timeout=REQUEST_TIMEOUT)
            resp.raise_for_status()
            return resp
        except requests.RequestException as exc:  # pragma: no cover - network
            last_exc = exc
            log.warning("GDC request failed (attempt %d/%d): %s", attempt, RETRY_ATTEMPTS, exc)
            time.sleep(RETRY_BACKOFF_SECONDS * attempt)
    raise RuntimeError(f"GDC request to {url} failed after {RETRY_ATTEMPTS} attempts") from last_exc


def _get_with_retry(url: str, **kwargs) -> requests.Response:
    last_exc: Exception | None = None
    for attempt in range(1, RETRY_ATTEMPTS + 1):
        try:
            resp = requests.get(url, timeout=REQUEST_TIMEOUT, **kwargs)
            resp.raise_for_status()
            return resp
        except requests.RequestException as exc:  # pragma: no cover - network
            last_exc = exc
            log.warning("GDC GET failed (attempt %d/%d): %s", attempt, RETRY_ATTEMPTS, exc)
            time.sleep(RETRY_BACKOFF_SECONDS * attempt)
    raise RuntimeError(f"GDC GET {url} failed after {RETRY_ATTEMPTS} attempts") from last_exc


# --------------------------------------------------------------------------- #
# File discovery
# --------------------------------------------------------------------------- #
def query_rna_seq_files(cfg: dict[str, Any]) -> pd.DataFrame:
    """Query the GDC ``files`` endpoint for RNA-seq gene expression files.

    Returns a DataFrame with one row per file, including the associated
    case (patient) submitter ID needed to later join clinical data.
    """
    gdc_cfg = cfg["gdc"]
    base_url = gdc_cfg["base_url"]
    max_cases = gdc_cfg.get("max_cases")

    filters = {
        "op": "and",
        "content": [
            {"op": "in", "content": {"field": "cases.project.project_id", "value": [cfg["project"]["cancer_type"]]}},
            {"op": "in", "content": {"field": "data_category", "value": [gdc_cfg["data_category"]]}},
            {"op": "in", "content": {"field": "data_type", "value": [gdc_cfg["data_type"]]}},
            {"op": "in", "content": {"field": "analysis.workflow_type", "value": [gdc_cfg["workflow_type"]]}},
            {"op": "in", "content": {"field": "experimental_strategy", "value": [gdc_cfg["experimental_strategy"]]}},
            {"op": "in", "content": {"field": "cases.samples.sample_type", "value": gdc_cfg["sample_type"]}},
        ],
    }

    fields = [
        "file_id",
        "file_name",
        "cases.case_id",
        "cases.submitter_id",
        "cases.samples.sample_type",
        "cases.samples.submitter_id",
    ]

    payload = {
        "filters": filters,
        "fields": ",".join(fields),
        "format": "JSON",
        "size": max_cases if max_cases else 20000,
    }

    log.info("Querying GDC files endpoint for %s RNA-seq gene expression files...", cfg["project"]["cancer_type"])
    resp = _post_with_retry(base_url + GDC_FILES_ENDPOINT, payload)
    hits = resp.json()["data"]["hits"]
    log.info("GDC returned %d candidate files.", len(hits))

    records = []
    for h in hits:
        case = h.get("cases", [{}])[0]
        samples = case.get("samples", [{}])
        sample = samples[0] if samples else {}
        records.append(
            {
                "file_id": h["file_id"],
                "file_name": h["file_name"],
                "case_id": case.get("case_id"),
                "case_submitter_id": case.get("submitter_id"),
                "sample_type": sample.get("sample_type"),
                "sample_submitter_id": sample.get("submitter_id"),
            }
        )
    df = pd.DataFrame(records).drop_duplicates(subset="case_submitter_id")
    if max_cases:
        df = df.head(max_cases)
    log.info("Selected %d unique cases after de-duplication / max_cases cap.", len(df))
    return df.reset_index(drop=True)


# --------------------------------------------------------------------------- #
# File download + parsing
# --------------------------------------------------------------------------- #
def download_expression_file(base_url: str, file_id: str) -> pd.DataFrame:
    """Download and parse one STAR-Counts gene expression TSV from GDC.

    GDC STAR-Counts files are gzip-compressed TSVs with a header comment
    block followed by columns: gene_id, gene_name, gene_type,
    unstranded, stranded_first, stranded_second, tpm_unstranded,
    fpkm_unstranded, fpkm_uq_unstranded.
    """
    url = f"{base_url}{GDC_DATA_ENDPOINT}/{file_id}"
    resp = _get_with_retry(url)
    raw_bytes = resp.content
    try:
        text = gzip.decompress(raw_bytes).decode("utf-8")
    except OSError:
        text = raw_bytes.decode("utf-8")

    df = pd.read_csv(
        io.StringIO(text),
        sep="\t",
        comment="#",
        skiprows=1,  # first non-comment line is the real header in STAR-Counts files
        header=None,
        names=[
            "gene_id",
            "gene_name",
            "gene_type",
            "unstranded",
            "stranded_first",
            "stranded_second",
            "tpm_unstranded",
            "fpkm_unstranded",
            "fpkm_uq_unstranded",
        ],
    )
    # Drop the four summary rows GDC prepends (N_unmapped, N_multimapping, ...)
    df = df[~df["gene_id"].astype(str).str.startswith("N_")]
    df = df[df["gene_type"] == "protein_coding"]
    return df.set_index("gene_id")


def build_expression_matrix(
    files_df: pd.DataFrame, cfg: dict[str, Any], raw_dir: Path
) -> pd.DataFrame:
    """Download every file in ``files_df`` and assemble a genes x samples matrix."""
    gdc_cfg = cfg["gdc"]
    value_col = gdc_cfg["value_column"]
    base_url = gdc_cfg["base_url"]

    columns = {}
    gene_names: pd.Series | None = None
    n = len(files_df)
    for i, row in files_df.iterrows():
        cached_path = raw_dir / f"{row['file_id']}.tsv"
        if cached_path.exists():
            gene_df = pd.read_csv(cached_path, sep="\t", index_col=0)
        else:
            log.info("[%d/%d] Downloading %s (%s)", i + 1, n, row["file_name"], row["case_submitter_id"])
            gene_df = download_expression_file(base_url, row["file_id"])
            gene_df.to_csv(cached_path, sep="\t")
        columns[row["case_submitter_id"]] = gene_df[value_col]
        if gene_names is None:
            gene_names = gene_df["gene_name"]

    expr = pd.DataFrame(columns)
    expr.insert(0, "gene_name", gene_names)
    return expr


# --------------------------------------------------------------------------- #
# Clinical metadata
# --------------------------------------------------------------------------- #
def query_clinical_metadata(case_submitter_ids: list[str], cfg: dict[str, Any]) -> pd.DataFrame:
    """Pull demographic, diagnosis, and follow-up fields for survival analysis."""
    base_url = cfg["gdc"]["base_url"]

    filters = {
        "op": "in",
        "content": {"field": "submitter_id", "value": case_submitter_ids},
    }
    fields = [
        "submitter_id",
        "demographic.gender",
        "demographic.sex_at_birth",
        "demographic.age_at_index",
        "demographic.vital_status",
        "demographic.days_to_death",
        "demographic.days_to_birth",
        "diagnoses.ajcc_pathologic_stage",
        "diagnoses.tumor_grade",
        "diagnoses.days_to_last_follow_up",
        "diagnoses.morphology",
        "diagnoses.primary_diagnosis",
    ]
    payload = {
        "filters": filters,
        "fields": ",".join(fields),
        "format": "JSON",
        "size": len(case_submitter_ids),
    }
    log.info("Querying GDC cases endpoint for clinical metadata on %d cases...", len(case_submitter_ids))
    resp = _post_with_retry(base_url + GDC_CASES_ENDPOINT, payload)
    hits = resp.json()["data"]["hits"]

    records = []
    for h in hits:
        demo = h.get("demographic", {}) or {}
        diag_list = h.get("diagnoses", [{}]) or [{}]
        diag = diag_list[0] if diag_list else {}
        days_to_death = demo.get("days_to_death")
        days_to_last_follow_up = diag.get("days_to_last_follow_up")
        vital_status = demo.get("vital_status")
        time_to_event = days_to_death if days_to_death is not None else days_to_last_follow_up
        records.append(
            {
                "case_submitter_id": h.get("submitter_id"),
                "gender": demo.get("gender") or demo.get("sex_at_birth"),
                "age_at_index": demo.get("age_at_index"),
                "vital_status": vital_status,
                "ajcc_pathologic_stage": diag.get("ajcc_pathologic_stage"),
                "tumor_grade": diag.get("tumor_grade"),
                "primary_diagnosis": diag.get("primary_diagnosis"),
                "days_to_death": days_to_death,
                "days_to_last_follow_up": days_to_last_follow_up,
                "days_to_event": time_to_event,
                "event_observed": 1 if vital_status == "Dead" else 0,
            }
        )
    return pd.DataFrame(records)


# --------------------------------------------------------------------------- #
# Orchestration
# --------------------------------------------------------------------------- #
def run_download(cfg: dict[str, Any] | None = None) -> tuple[Path, Path]:
    """End-to-end real GDC download: expression matrix + clinical metadata.

    Returns paths to the written expression matrix and clinical metadata CSVs.
    """
    cfg = cfg or load_config()
    raw_dir = resolve_path(cfg, "processed_dir").parent / "raw"
    raw_dir.mkdir(parents=True, exist_ok=True)
    metadata_dir = resolve_path(cfg, "metadata_dir")

    files_df = query_rna_seq_files(cfg)
    files_df.to_csv(metadata_dir / "gdc_file_manifest.csv", index=False)

    expr = build_expression_matrix(files_df, cfg, raw_dir)
    expr_path = raw_dir / f"{cfg['project']['cancer_type']}_expression_matrix.tsv"
    expr.to_csv(expr_path, sep="\t")
    log.info("Wrote expression matrix: %s (%d genes x %d samples)", expr_path, expr.shape[0], expr.shape[1] - 1)

    clinical_df = query_clinical_metadata(files_df["case_submitter_id"].tolist(), cfg)
    clinical_path = metadata_dir / f"{cfg['project']['cancer_type']}_clinical.csv"
    clinical_df.to_csv(clinical_path, index=False)
    log.info("Wrote clinical metadata: %s (%d cases)", clinical_path, len(clinical_df))

    return expr_path, clinical_path


TCGABIOLINKS_SCRIPT = r'''#!/usr/bin/env Rscript
# =============================================================================
# download_tcgabiolinks.R
#
# Equivalent full-scale data acquisition using TCGAbiolinks, the standard
# Bioconductor package used across the TCGA/GDC research community. Prefer
# this route for a production-scale pull of an entire project (e.g. all
# ~1,100 TCGA-BRCA cases); use src/download.py for lightweight, dependency-free
# Python access or CI smoke tests.
# =============================================================================

if (!requireNamespace("BiocManager", quietly = TRUE))
    install.packages("BiocManager")
if (!requireNamespace("TCGAbiolinks", quietly = TRUE))
    BiocManager::install("TCGAbiolinks")

library(TCGAbiolinks)
library(SummarizedExperiment)

project   <- "TCGA-BRCA"
out_dir   <- file.path("data", "raw")
meta_dir  <- file.path("data", "metadata")
dir.create(out_dir,  recursive = TRUE, showWarnings = FALSE)
dir.create(meta_dir, recursive = TRUE, showWarnings = FALSE)

message("Querying GDC for ", project, " RNA-seq (STAR - Counts) ...")
query <- GDCquery(
    project       = project,
    data.category = "Transcriptome Profiling",
    data.type     = "Gene Expression Quantification",
    workflow.type = "STAR - Counts",
    sample.type   = "Primary Tumor"
)
GDCdownload(query, directory = out_dir, method = "api")
data <- GDCprepare(query, directory = out_dir)

expr_tpm <- assay(data, "tpm_unstrand")
write.table(
    expr_tpm,
    file = file.path(out_dir, paste0(project, "_expression_matrix_full.tsv")),
    sep = "\t", quote = FALSE, col.names = NA
)

message("Querying matched clinical data ...")
clinical <- GDCquery_clinic(project = project, type = "clinical")
write.csv(
    clinical,
    file = file.path(meta_dir, paste0(project, "_clinical_full.csv")),
    row.names = FALSE
)

message("Done. Expression matrix and clinical table written to data/raw and data/metadata.")
'''


def write_tcgabiolinks_script(dest: str | Path = "scripts/download_tcgabiolinks.R") -> Path:
    """Materialize the companion R/TCGAbiolinks script referenced in the README."""
    from .config import REPO_ROOT

    path = REPO_ROOT / dest
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(TCGABIOLINKS_SCRIPT, encoding="utf-8")
    return path


if __name__ == "__main__":
    run_download()
